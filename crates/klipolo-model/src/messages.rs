//! The model's codes and their English (`coded`). Every `invalid`, `check`, `check_with` and `not_found` in this
//! crate names one; `msg!` and `code!` refuse to compile a code that isn't here.

use crate::coded::Messages;

macro_rules! msg {
    ($($t:tt)*) => { $crate::coded_msg!($crate::messages::MESSAGES, $($t)*) };
}
macro_rules! code {
    ($c:literal) => {
        $crate::coded_code!($crate::messages::MESSAGES, $c)
    };
}
pub(crate) use {code, msg};

